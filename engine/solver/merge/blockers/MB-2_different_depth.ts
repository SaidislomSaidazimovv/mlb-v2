// MB-2 — Разная глубина
//
// Общий бок физически один щит одной глубины. У шкафов 560 и 350 общего бока быть не может — он был бы либо слишком коротким для одного, либо торчал бы у другого.

import type { MergeBlocker } from "../types.js";

export const MB_2: MergeBlocker = {
  id: "MB-2",
  title: "Разная глубина",
  why: "Общий бок физически один щит одной глубины. У шкафов 560 и 350 общего бока быть не может — он был бы либо слишком коротким для одного, либо торчал бы у другого.",
  source: "Физика. НЕ настройка",
  blocks(c) {
    const a = c.left.size?.d_mm10 ?? 0, b = c.right.size?.d_mm10 ?? 0;
    if (a !== b) return `разная глубина: ${a / 10}мм и ${b / 10}мм — общий бок был бы одной глубины для обоих`;
    return null;
  },
};
