// MB-5 — Разный материал
//
// Общий бок вырезается из ОДНОГО листа одного декора. Если шкафы берут материал из разных слотов палитры, у щита нет одного материала.

import type { MergeBlocker } from "../types.js";

export const MB_5: MergeBlocker = {
  id: "MB-5",
  title: "Разный материал",
  why: "Общий бок вырезается из ОДНОГО листа одного декора. Если шкафы берут материал из разных слотов палитры, у щита нет одного материала.",
  source: "DB/40 — палитра, слоты A/B/C/W",
  blocks(c) {
    if (c.left.roleSlot !== c.right.roleSlot)
      return `разные слоты материала (${c.left.roleSlot ?? "—"} и ${c.right.roleSlot ?? "—"}) — у общего щита один декор`;
    return null;
  },
};
